export type CaseSeverity = 'Low' | 'Medium' | 'High' | 'Critical'
export type CaseStatus = 'Open' | 'Active' | 'Under Review' | 'Closed'

// NEW: Victim-profile attributes for algorithm
export type LocationType = 'Home' | 'Street' | 'Park' | 'Vehicle' | 'Alley' | 'Warehouse' | 'Hotel' | 'Office' | 'Riverfront' | 'Highway' | 'Apartment' | 'Forest'
export type MethodType = 'Stabbing' | 'Strangulation' | 'Shooting' | 'Blunt force' | 'Poisoning' | 'Suffocation' | 'Dismemberment' | 'Asphyxiation'
export type VictimGender = 'Male' | 'Female' | 'Other' | 'Unknown'
export type AgeRange = '0-12' | '13-17' | '18-24' | '25-34' | '35-44' | '45-54' | '55-64' | '65+'

export type CaseSummary = {
  id: string
  title: string
  image: string
  severity: CaseSeverity
  victimType: string
  status: CaseStatus
  lastUpdated: string
  location: string
  time: string
  summary: string
  suspects: string[]
  relatedCaseIds: string[]
  riskScore: number
  
  // NEW: Victim-profile attributes for algorithm
  victimGender: VictimGender
  victimAgeMin: number
  victimAgeMax: number
  victimAgeRange: AgeRange
  locationType: LocationType
  method: MethodType
}

export type Profile = {
  id: string
  name: string
  alias: string
  age: number
  threatLevel: 'Moderate' | 'High' | 'Critical'
  lastSeen: string
  role: string
}

export type EvidenceEntry = {
  id: string
  caseId: string
  category: 'behavioral' | 'physical'
  title: string
  description: string
  note: string
}

export type TimelineEvent = {
  id: string
  caseId: string
  timestamp: string
  title: string
  detail: string
}

export type Relationship = {
  sourceCaseId: string
  targetCaseId: string
  similarity: number
  confidence: 'Low' | 'Medium' | 'High'
  note: string
}

export type ActivityFeedItem = {
  id: string
  timestamp: string
  description: string
}

